import type { Scenario, Difficulty } from '@/types/scenario';
import { nextjsInfo, nextjsRubric } from './shared';

type Case = [string, unknown, unknown];
function model(
  slug: string,
  title: string,
  difficulty: Difficulty,
  chapter: string,
  contract: string,
  code: string,
  cases: Case[],
  explanation: string,
  tweak: string,
  answer: string,
  doc: string,
): Scenario {
  const id = `next-lab-${slug}`;
  return {
    id,
    title,
    difficulty,
    topic: 'Next.js',
    subtopic: chapter,
    type: 'coding',
    estimatedMinutes: difficulty === 'Beginner' ? 20 : 35,
    businessContext:
      'Implement a deterministic application policy used around a Next.js request boundary. The Worker executes your policy function, not a Next.js server.',
    problemStatement: `Implement solution(input). ${contract}`,
    codeLanguage: 'javascript',
    javascriptExercise: true,
    starterCode:
      'function solution(input) {\n  // Implement the documented policy without mutating input.\n  return null;\n}',
    constraints: [
      'Return exactly the documented JSON value, including every field.',
      'Do not mutate input. Inputs follow the shapes described in the task.',
      'These tests do not establish RSC rendering, cache invalidation, distributed concurrency or server authorization.',
    ],
    candidateTasks: [
      'Implement the policy and trace every boundary case.',
      'Explain where this function would run in a Next.js application and which checks remain server-side.',
      'Answer the interview variation without changing the base contract.',
    ],
    testCases: cases.map(([name, input, expected], index) => ({
      id: `${id}-${index + 1}`,
      name,
      inputDescription: JSON.stringify(input),
      expectedOutput: JSON.stringify(expected),
    })),
    hints: [
      explanation.split('. ')[0] + '.',
      'Trace the smallest empty, repeated or invalid case before adding branches.',
    ],
    rubric: nextjsRubric(id, contract),
    referenceSolution: {
      explanation,
      codeOrArtifact: code,
      architectureNotes:
        'Pure application-policy model. Integrate and verify against the real server separately.',
    },
    alternativeApproaches: [answer],
    commonMistakes: [
      'Treating a passing model as proof of framework or distributed-system behavior.',
      'Silently coercing values outside the explicitly allowed input policy.',
    ],
    followUpQuestions: [
      {
        id: `${id}-extension`,
        question: tweak,
        expectedConcepts: [
          'Changed contract',
          'Boundary evidence',
          'Server ownership',
        ],
        sampleStrongAnswer: answer,
      },
    ],
    nextjsPractice: nextjsInfo(chapter, 'policy', doc, [
      'Run every exact-result case.',
      'Run the same policy at its real request boundary and test forged/untrusted inputs separately.',
    ]),
  };
}

